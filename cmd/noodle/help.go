package main

import (
	"flag"
	"fmt"
	"io"
	"strings"
)

type commandDoc struct {
	synopsis string
	about    string
	flags    *flag.FlagSet
}

func newListIconsFlags() (set *flag.FlagSet, icons *string, list *bool) {
	set = flag.NewFlagSet("noodle", flag.ExitOnError)
	icons = set.String("icons", "", "comma-separated directories of extra <name>.svg icons, searched before the built-in ones")
	list = set.Bool("list-icons", false, "print the available icon names and exit")
	return set, icons, list
}

func commandDocs() []commandDoc {
	adapterNames := "k8s"
	if reg, err := adapters(); err == nil {
		adapterNames = strings.Join(reg.Names(), ", ")
	}
	listIcons, _, _ := newListIconsFlags()
	return []commandDoc{
		{"noodle render DIR", "Check a view and its lint; with -o, write it as a draw.io file. A sequence view is checked on its participants only.", newRenderFlags().set},
		{"noodle discover ADAPTER [PATH…|-]", "Read infrastructure files (no path or - reads stdin) and write a fragment of what they define. Adapters: " + adapterNames + ".", newDiscoverFlags().set},
		{"noodle migrate SPEC.yaml DIR", "Convert a v0 single file to a v1alpha1 system, and write nothing unless it draws the same diagram.", nil},
		{"noodle setup opencode|codex", "Write the noodle-diagram skill and the subagents where OpenCode or Codex read them. Exactly one of -project and -user; -project takes an optional DIR.", newSetupFlags().set},
		{"noodle version", "Print the version set at build time: a release tag, a Nix revision, or dev.", nil},
		{"noodle help", "Print this reference. With -markdown, print docs/guide/cli.md.", nil},
		{"noodle -list-icons", "List the icon names a view can use.", listIcons},
	}
}

// fullUsage is the text of "noodle help" and the source of docs/guide/cli.md.
func fullUsage() string {
	var b strings.Builder
	b.WriteString(usage + "\n")
	for _, c := range commandDocs() {
		fmt.Fprintf(&b, "\n%s\n  %s\n", c.synopsis, c.about)
		if c.flags == nil {
			continue
		}
		var defaults strings.Builder
		c.flags.SetOutput(&defaults)
		c.flags.PrintDefaults()
		b.WriteString(defaults.String())
	}
	return b.String()
}

const cliReferenceHeader = "# CLI reference\n\nGenerated by `make cli-doc` from the output of `noodle help`; do not edit it by hand.\n`go test ./cmd/noodle/` fails when this page differs from that output.\n\n"

func cliReference() string {
	return cliReferenceHeader + "```text\n" + fullUsage() + "```\n"
}

// checkCLIReference compares the committed page with what the binary prints.
func checkCLIReference(committed string) error {
	if committed != cliReference() {
		return fmt.Errorf("docs/guide/cli.md differs from the usage text of noodle help: run make cli-doc")
	}
	return nil
}

func helpCommand(args []string, stdout io.Writer) error {
	switch {
	case len(args) == 0:
		_, err := io.WriteString(stdout, fullUsage())
		return err
	case len(args) == 1 && args[0] == "-markdown":
		_, err := io.WriteString(stdout, cliReference())
		return err
	}
	return fmt.Errorf("usage: noodle help [-markdown]")
}
